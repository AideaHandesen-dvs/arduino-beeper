#!/usr/bin/env python3
import serial
import time

ser = serial.Serial('/dev/ttyUSB0', 9600)
time.sleep(0.5)

# スーパーマリオブラザーズ ゴールファンファーレ（旗のポール）
# ソドミソドミ ソーミー / ラ♭ドミ♭ラ♭ドミ♭ ラ♭ーミ♭ー / シ♭レファシ♭レファ シ♭ー シ♭シ♭シ♭ ドーー
# (待ち ms, 周波数 Hz, 長さ ms)。待ちは前の音が鳴り終わってから次を送るまで。
notes = [
    (0, 392, 100),    # G4
    (10, 523, 100),   # C5
    (10, 659, 100),   # E5
    (10, 784, 100),   # G5
    (10, 1047, 100),  # C6
    (10, 1319, 100),  # E6
    (10, 1568, 300),  # G6
    (30, 1319, 300),  # E6

    (30, 415, 100),   # Ab4
    (10, 523, 100),   # C5
    (10, 622, 100),   # Eb5
    (10, 831, 100),   # Ab5
    (10, 1047, 100),  # C6
    (10, 1245, 100),  # Eb6
    (10, 1661, 300),  # Ab6
    (30, 1245, 300),  # Eb6

    (30, 466, 100),   # Bb4
    (10, 587, 100),   # D5
    (10, 698, 100),   # F5
    (10, 932, 100),   # Bb5
    (10, 1175, 100),  # D6
    (10, 1397, 100),  # F6
    (10, 1865, 300),  # Bb6
    (30, 1865, 100),  # Bb6
    (10, 1865, 100),  # Bb6
    (10, 1865, 100),  # Bb6
    (10, 2093, 700),  # C7
]

for wait, freq, dur in notes:
    if wait > 0:
        time.sleep(wait / 1000)
    ser.write(f'F{freq}D{dur}\n'.encode())
    time.sleep(dur / 1000)

ser.close()
print("Done!")
